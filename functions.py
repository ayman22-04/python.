# Function without Parameters
def greet():
    print("Hello! Welcome to Python.")

# Function with Parameters
def add(a, b):
    return a + b

def multiply(a, b):
    return a * b

def square(n):
    return n * n

greet()

print("Addition:", add(10, 5))
print("Multiplication:", multiply(10, 5))
print("Square:", square(4))

print("Program Finished Successfully!")